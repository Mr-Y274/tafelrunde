function index() {
  const map: Record<Transit, Map<number, number[]>> = {
    taxi: new Map(),
    bus: new Map(),
    ug: new Map(),
    water: new Map(),
  };
  for (const station of STATIONS) {
    map.taxi.set(station.id, []);
    map.bus.set(station.id, []);
    map.ug.set(station.id, []);
    map.water.set(station.id, []);
  }
  for (const [mode, a, b] of EDGES) {
    const left = map[mode].get(a);
    const right = map[mode].get(b);
    if (!left || !right) continue;
    left.push(b);
    right.push(a);
  }
  return map;
}

const LINKS = index();

export function links(id: number, mode: Transit): number[] {
  return LINKS[mode].get(id) ?? [];
}

export function station(id: number) {
  return STATIONS.find((item) => item.id === id);
}

export function isStart(id: number) {
  return (STARTS as readonly number[]).includes(id);
}

export const SEGMENTS: { a: number; b: number; mode: Transit }[] = (["taxi", "bus", "ug", "water"] as Transit[]).flatMap(
  (mode) => {
    const seen = new Set<string>();
    const out: { a: number; b: number; mode: Transit }[] = [];
    for (const [from, tos] of LINKS[mode]) {
      for (const to of tos) {
        const key = from < to ? `${from}-${to}` : `${to}-${from}`;
        if (seen.has(key)) continue;
        seen.add(key);
        out.push({ a: Math.min(from, to), b: Math.max(from, to), mode });
      }
    }
    return out;
  },
);

export function allStationsConnected() {
  const seen = new Set<number>([1]);
  const queue = [1];
  while (queue.length) {
    const id = queue.pop()!;
    const next = new Set<number>([
      ...links(id, "taxi"),
      ...links(id, "bus"),
      ...links(id, "ug"),
      ...links(id, "water"),
    ]);
    for (const n of next) {
      if (!seen.has(n)) {
        seen.add(n);
        queue.push(n);
      }
    }
  }
  return seen.size === STATIONS.length;
}
